// popup_frame.js
// Меню в панели на странице лежит в iframe и должно занять его целиком, а в
// окне попапа — держать размер 800×600 (больше браузер попапу не даёт).
// Обычный скрипт в <head>: popup_loader.js — модуль и выполняется после
// разбора страницы, класс оттуда приходил поздно, и меню успевало моргнуть
// в размере попапа.
document.documentElement.classList.toggle('in-frame', window.self !== window.top);
